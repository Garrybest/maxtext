"""Inspect and dump samples from antllm .scatter/.lazy datasets.

Similar to antllm's data/tools/check_outputs.py but works standalone
with direct directory paths — no YAML config or training framework needed.

Usage examples:

  # Dump first 5 samples from a single scatter directory (sliding_window)
  python check_lazy_outputs.py --scatter-dir /path/to/dataset.scatter --num-samples 5

  # Dump with specific seq_length and eos_token_id
  python check_lazy_outputs.py --scatter-dir /path/to/dataset.scatter \
      --seq-length 4096 --eos-token-id 2 --num-samples 10

  # Dump from multiple datasets with blending weights
  python check_lazy_outputs.py \
      --scatter-dir /path/to/ds1.scatter /path/to/ds2.scatter \
      --weights 0.7 0.3 --num-samples 20

  # Use map mode with index_mapping
  python check_lazy_outputs.py --scatter-dir /path/to/dataset.scatter \
      --mode map --index-mapping-path /path/to/index_mapping_dir

  # Decode tokens with a tokenizer
  python check_lazy_outputs.py --scatter-dir /path/to/dataset.scatter \
      --tokenizer-path /path/to/tokenizer --num-samples 3

  # Save output to numpy files
  python check_lazy_outputs.py --scatter-dir /path/to/dataset.scatter \
      --num-samples 100 --output-dir /tmp/check_outputs

  # Dump ALL scatter groups (for comparison with antllm check_outputs.py)
  # Each group outputs to <output-dir>/<group_id>/step_*.npy
  python check_lazy_outputs.py --scatter-dir /path/to/dataset.scatter \
      --loader-scatter -4 --batch-per-step 8 --num-steps 10 \
      --dump-groups --output-dir /tmp/maxtext_groups

  # Load all parameters from a JSON config file (generated by antllm check_outputs.py)
  python check_lazy_outputs.py --config /tmp/antllm_dump/maxtext_params.json \
      --dump-groups --num-steps 10 --output-dir /tmp/maxtext_dump
"""

