# JSON key -> argparse dest (only for non-obvious mappings)
_CONFIG_KEY_MAP = {
    "scatter_dirs": "scatter_dir",
    "loader_mode": "mode",
}

# argparse defaults that should NOT be treated as "user explicitly set"
# when deciding whether CLI overrides config. We track which args the user
# actually provided on the command line via _CLI_SENTINEL.
_CLI_SENTINEL = object()


def _load_config(config_path):
  """Load JSON config file and return as dict."""
  with open(config_path, encoding="utf-8") as f:
    return json.load(f)


def _apply_config(args, config, parser):
  """Apply config dict values to args, with CLI args taking precedence.

  For each key in config, map it to the argparse dest name, and set it on
  args only if the user did not explicitly provide that arg on the CLI.
  """
  # Build set of args the user explicitly provided on CLI
  # by comparing against the sentinel defaults we injected
  cli_provided = set()
  for action in parser._actions:
    if action.dest == "help":
      continue
    val = getattr(args, action.dest, _CLI_SENTINEL)
    if val is not _CLI_SENTINEL and val != action.default:
      cli_provided.add(action.dest)
  # Special: scatter_dir is None by default, so if user passed it, it's non-None
  if args.scatter_dir is not None:
    cli_provided.add("scatter_dir")

  for key, value in config.items():
    if value is None:
      continue
    dest = _CONFIG_KEY_MAP.get(key, key)
    # micro_batch_size -> batch_per_step (fallback)
    if key == "micro_batch_size" and "batch_per_step" not in config:
      dest = "batch_per_step"
    elif key == "micro_batch_size":
      continue  # batch_per_step in config takes precedence
    # drop_last (bool) -> no_drop_last (inverted)
    if key == "drop_last":
      dest = "no_drop_last"
      value = not value
    # Skip keys we don't recognize
    if not hasattr(args, dest):
      continue
    # CLI takes precedence
    if dest in cli_provided:
      continue
    setattr(args, dest, value)


