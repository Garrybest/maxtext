def _resolve_mode_for_tool(args, scatter_dir: str) -> str:
  """Resolve loader mode for a scatter_dir, supporting per-dataset pack via --bfd-pack."""
  bfd_pack = getattr(args, "bfd_pack", None)
  if not bfd_pack:
    return args.mode
  ds_name = os.path.basename(scatter_dir).replace(".scatter", "")
  if bfd_pack == "ALL" or ds_name in {n.strip() for n in bfd_pack.split(",")}:
    return "pack"
  return "sliding_window"


def build_source(args):
  """Build data source(s) from command-line arguments.

  Replicates the antllm pipeline order:
    1. Build per-scatter MultiShardLazyDataSource
    2. Wrap in LazyBlendedDataSource (even single dataset, if shuffle-seed given)
    3. Apply split (train/valid/test)
  """
  # antllm convention: internal seq_length = user_seq_length + 1
  effective_seq = args.seq_length + 1
  cls_token_id = args.cls_token_id if args.cls_token_id >= 0 else None
  drop_last = not args.no_drop_last

  sources = []
  for scatter_dir in args.scatter_dir:
    mode = _resolve_mode_for_tool(args, scatter_dir)
    source = MultiShardLazyDataSource(
        scatter_dir=scatter_dir,
        mode=mode,
        seq_length=effective_seq,
        eos_token_id=args.eos_token_id,
        data_type=args.data_type,
        cls_token_id=cls_token_id,
        add_cls=args.add_cls,
        drop_last=drop_last,
        loader_online_shuffle=args.loader_online_shuffle,
        loader_seed=args.loader_seed,
        index_mapping_path=args.index_mapping_path,
        bin_index_base_path=args.bin_index_path,
        bfd_pack_sort_by_lens=args.bfd_pack_sort_by_lens,
        loader_scatter=args.loader_scatter,
        process_index=args.process_index,
    )
    per_shard = [len(l) for l in source._loaders]
    print(f"  [{scatter_dir}] shards={len(source._loaders)}, samples={len(source)}")
    print(f"  per_shard_samples: {per_shard}")
    print(f"  cnt_ends: {source._cnt_ends.tolist()}")
    sources.append(source)

  # Blending (or single-dataset with shuffle)
  if len(sources) > 1 or args.shuffle_seed > 0:
    raw_weights = args.weights
    if raw_weights is None:
      raw_weights = [1.0] * len(sources)
    if len(raw_weights) != len(sources):
      raise ValueError(f"Number of weights ({len(raw_weights)}) must match scatter-dirs ({len(sources)})")

    # Compute total_size and normalize weights (matching antllm configure_data.py)
    if args.weight_mode == "epoch":
      # antllm epoch mode: size = int(sum(w * len(ds))), normalize by int(sum)
      # matching antllm configure_data.py:265
      weighted = [w * len(s) for w, s in zip(raw_weights, sources)]
      total = sum(weighted)
      total_size = int(total)
      weights = np.array([w / total_size for w in weighted], dtype=np.float64)
    else:
      weights = np.array(raw_weights, dtype=np.float64)
      weights = weights / weights.sum()
      total_size = sum(len(s) for s in sources)

    print(f"  Blending: weight_mode={args.weight_mode}, raw_weights={raw_weights}")
    print(
        f"  Blending: norm_weights={weights.tolist()}, total_size={total_size},"
        f" shuffle_seed={args.shuffle_seed}, shuffle_only_dataset={args.shuffle_only_dataset}"
    )
    result = LazyBlendedDataSource(
        sources,
        weights,
        total_size,
        shuffle_seed=args.shuffle_seed,
        shuffle_only_dataset=args.shuffle_only_dataset,
        cache_dir=args.blend_cache_dir,
        process_index=args.process_index,
        loader_scatter=args.loader_scatter,
    )
    # Print first few indices for cross-checking with antllm
    print(f"  dataset_index[:10]: {result.dataset_index[:10].tolist()}")
    print(f"  dataset_sample_index[:10]: {result.dataset_sample_index[:10].tolist()}")
  else:
    result = sources[0]

  # Split (antllm split: "999,1,0" -> train 99.9%, valid 0.1%, test 0%)
  if args.split:
    split_ratios = _parse_split(args.split)
    if split_ratios is not None:
      parts = _split_source(result, split_ratios)
      part_names = ["train", "valid", "test"]
      requested = {p.strip() for p in args.split_parts.split(",")}
      split_results = {}
      for i, name in enumerate(part_names):
        if parts[i] is not None:
          print(f"  Split {args.split} -> {name}={len(parts[i])} samples")
          if name in requested:
            split_results[name] = parts[i]
      if split_results:
        return split_results
      # Fallback: no requested parts found, return train
      if parts[0] is not None:
        return {"train": parts[0]}

  return {"train": result}


def _parse_split(split_str):
  """Parse split ratio string like '999,1,0' into normalized [train, valid, test]."""
  parts = split_str.replace("/", ",").split(",")
  splits = [float(s) for s in parts]
  while len(splits) < 3:
    splits.append(0.0)
  splits = splits[:3]
  total = sum(splits)
  return [s / total for s in splits]


def _split_source(source, split_ratios):
  """Split a source into train/valid/test by ratio."""
  total = len(source)
  start_idx = 0
  residual_idx = 0.0
  results = [None, None, None]
  for i, ratio in enumerate(split_ratios):
    if ratio != 0:
      proportion = total * ratio
      residual_idx += proportion % 1
      split_size = int(int(proportion) + residual_idx)
      results[i] = _SliceSource(source, start_idx, start_idx + max(split_size, 1))
      start_idx += split_size
      residual_idx %= 1
  return results


class _SliceSource:
  """Read-only slice of a data source."""

  def __init__(self, source, start, end):
    self._source = source
    self._start = start
    self._size = end - start

  def __len__(self):
    return self._size

  def __getitem__(self, idx):
    return self._source[idx % self._size + self._start]


def print_dataset_stats(source, args):
  """Print dataset statistics."""
  print("=" * 60)
  print("Dataset Statistics")
  print("=" * 60)
  print(f"  Scatter dir(s):   {args.scatter_dir}")
  print(f"  Mode:             {args.mode}")
  print(f"  Seq length:       {args.seq_length} (internal: {args.seq_length + 1})")
  print(f"  EOS token ID:     {args.eos_token_id}")
  print(f"  Total samples:    {len(source)}")
  if args.weights:
    print(f"  Blend weights:    {args.weights}")

  # Per-scatter stats
  for scatter_dir in args.scatter_dir:
    from pathlib import Path

    scatter_path = Path(scatter_dir)
    lazy_dirs = sorted(scatter_path.glob("*.lazy"), key=lambda p: int(p.stem))
    total_tokens = 0
    total_docs = 0
    for lazy_dir in lazy_dirs:
      ds = LazyIndexedDataset(str(lazy_dir), args.data_type)
      total_tokens += ds.total_tokens
      total_docs += ds.num_docs
      ds.close()
    print(f"\n  [{scatter_path.name}]")
    print(f"    Shards:         {len(lazy_dirs)}")
    print(f"    Total docs:     {total_docs:,}")
    print(f"    Total tokens:   {total_tokens:,}")
    if total_docs > 0:
      print(f"    Avg doc len:    {total_tokens / total_docs:.1f}")
  print("=" * 60)


def load_tokenizer(path):
  """Try to load a HuggingFace tokenizer."""
  try:
    from transformers import AutoTokenizer

    return AutoTokenizer.from_pretrained(path, trust_remote_code=True)
  except Exception as e:
    print(f"Warning: could not load tokenizer from {path}: {e}")
    return None


def dump_sample(index, sample, eos_token_id=2, tokenizer=None, decode=True):
  """Print a single sample."""
  tokens = sample["text"] if isinstance(sample, dict) else sample
  tokens = np.asarray(tokens)

  print(f"\n--- Sample {index} (length={len(tokens)}) ---")
  print(f"  Tokens[:30]: {tokens[:30].tolist()}")
  if len(tokens) > 30:
    print(f"  Tokens[-10:]: {tokens[-10:].tolist()}")

  # Token statistics
  unique, _ = np.unique(tokens, return_counts=True)
  eos_count = int(np.sum(tokens == eos_token_id))
  print(f"  Unique tokens: {len(unique)}, EOS count: {eos_count}")

  # Find EOS positions (document boundaries)
  eos_positions = np.where(tokens == eos_token_id)[0]
  if len(eos_positions) > 0:
    print(f"  EOS positions: {eos_positions.tolist()[:20]}{'...' if len(eos_positions) > 20 else ''}")

  # Decode if tokenizer available
  if tokenizer is not None and decode:
    try:
      text = tokenizer.decode(tokens.tolist(), skip_special_tokens=False)
      # Show first 200 chars
      preview = text[:200]
      if len(text) > 200:
        preview += "..."
      print(f"  Decoded: {repr(preview)}")
    except Exception as e:
      print(f"  Decode error: {e}")


def _trace_sample(source, global_idx):
  """Print routing trace for a sample through the pipeline."""
  from bisect import bisect_right as _bisect

  # Walk through the source chain
  src = source
  idx = global_idx

  # _SliceSource layer
  if hasattr(src, "_source") and hasattr(src, "_start"):
    mapped = idx % src._size + src._start
    print(f"    SliceSource: idx={idx} -> mapped={mapped} (start={src._start}, size={src._size})")
    src = src._source
    idx = mapped

  # LazyBlendedDataSource layer
  if hasattr(src, "_dataset_sample_index"):
    ds_idx = int(src._dataset_index[idx])
    sample_idx = int(src._dataset_sample_index[idx])
    inner_src = src._sources[ds_idx]
    local_idx = sample_idx % len(inner_src)
    print(f"    Blend: idx={idx} -> ds={ds_idx}, sample_idx={sample_idx}, local={local_idx} (src_len={len(inner_src)})")
    src = inner_src
    idx = local_idx

  # MultiShardLazyDataSource layer
  if hasattr(src, "_cnt_ends"):
    shard = _bisect(src._cnt_ends, idx)
    inner = idx - (int(src._cnt_ends[shard - 1]) if shard > 0 else 0)
    print(f"    MultiShard: local={idx} -> shard={shard}, inner={inner}")


def _debug_binary(scatter_dir, seq_length, eos_token_id, data_type, mode):
  """Print raw binary diagnostics for each shard in a scatter directory."""
  from pathlib import Path

  scatter_path = Path(scatter_dir)
  lazy_dirs = sorted(scatter_path.glob("*.lazy"), key=lambda p: int(p.stem))
  if not lazy_dirs:
    # Check for hash subdirectory
    sub_dirs = [d for d in scatter_path.iterdir() if d.is_dir() and not d.name.endswith(".lazy")]
    if len(sub_dirs) == 1:
      lazy_dirs = sorted(sub_dirs[0].glob("*.lazy"), key=lambda p: int(p.stem))
  if not lazy_dirs:
    print(f"  ERROR: No .lazy directories found in {scatter_dir}")
    return

  effective_seq = seq_length + 1
  print(f"\n{'='*60}")
  print(f"Binary Diagnostics for {scatter_dir}")
  print(f"  mode={mode}, seq_length={seq_length} (internal={effective_seq}), eos={eos_token_id}")
  print(f"  Found {len(lazy_dirs)} .lazy shards")
  print(f"{'='*60}")

  for shard_idx, lazy_dir in enumerate(lazy_dirs[:3]):  # First 3 shards
    print(f"\n--- Shard {shard_idx}: {lazy_dir.name} ---")
    bin_path = str(lazy_dir / data_type)
    lens_path = str(lazy_dir / f"{data_type}.lens.npy")

    # 1. Raw binary tokens
    try:
      fd = os.open(bin_path, os.O_RDONLY)
      raw_bytes = os.pread(fd, 120, 0)  # 30 int32 tokens
      os.close(fd)
      raw_tokens = np.frombuffer(raw_bytes, dtype=np.int32)
      print(f"  Raw binary first 30 tokens: {raw_tokens.tolist()}")
    except Exception as e:
      print(f"  ERROR reading binary: {e}")
      continue

    # 2. Document lengths
    try:
      lens = np.load(lens_path)
      ends = np.cumsum(lens)
      total_tokens = int(ends[-1])
      num_docs = len(lens)
      print(f"  num_docs={num_docs}, total_tokens={total_tokens}")
      print(f"  First 10 doc lengths: {lens[:10].tolist()}")
      print(f"  First 10 cumulative ends: {ends[:10].tolist()}")
    except Exception as e:
      print(f"  ERROR reading lens: {e}")
      continue

    # 3. LazyIndexedDataset read_range
    try:
      ds = LazyIndexedDataset(str(lazy_dir), data_type)
      range_tokens = ds.read_range(0, min(30, total_tokens))
      print(f"  read_range(0, 30): {range_tokens.tolist()}")
      ds.close()
    except Exception as e:
      print(f"  ERROR with read_range: {e}")

    # 4. Sliding window sample 0
    if mode == "sliding_window":
      try:
        ds = LazyIndexedDataset(str(lazy_dir), data_type)
        from maxtext.input_pipeline._lazy_datasource import LazySlidingWindowDataSource

        sw = LazySlidingWindowDataSource(ds, effective_seq, eos_token_id)
        if len(sw) > 0:
          sample0 = sw[0]
          tokens = sample0["text"] if isinstance(sample0, dict) else sample0
          tokens = np.asarray(tokens)
          print(f"  SlidingWindow[0] (len={len(tokens)}): first 30 = {tokens[:30].tolist()}")
          # Show where first EOS injection happens
          eos_pos = np.where(tokens == eos_token_id)[0]
          if len(eos_pos) > 0:
            first_eos = int(eos_pos[0])
            print(f"  First EOS at position {first_eos} (doc 0 length={int(lens[0])})")
        else:
          print(f"  SlidingWindow has 0 samples (total_tokens={total_tokens}, seq={effective_seq})")
        ds.close()
      except Exception as e:
        print(f"  ERROR with SlidingWindow: {e}")

  print(f"\n{'='*60}\n")


def _build_source_for_group(args, process_index):
  """Build a full-pipeline source (blend/shuffle/split) for a specific scatter group.

  Same as build_source() but overrides process_index for the given group.
  """
  saved_process_index = args.process_index
  args.process_index = process_index
  try:
    source = build_source(args)
  finally:
    args.process_index = saved_process_index
  return source


def _dump_split_source(source, split_name, base_dir, num_steps, batch_per_step):
  """Dump samples from a single source into base_dir/<group_id>/step_*.npy structure."""
  group_samples = len(source)
  print(f"    [{split_name}] samples={group_samples}")

  sample_count = 0
  for step in range(num_steps):
    step_tokens = []
    for j in range(batch_per_step):
      global_idx = step * batch_per_step + j
      if global_idx >= group_samples:
        global_idx = global_idx % group_samples
      sample = source[global_idx]
      tokens = sample["text"] if isinstance(sample, dict) else np.asarray(sample)
      tokens = np.asarray(tokens)[:-1]  # inputs = text[:-1]
      step_tokens.append(tokens)
      sample_count += 1

    batch_arr = np.stack(step_tokens, axis=0)
    np.save(os.path.join(base_dir, f"step_{step:06d}.npy"), batch_arr)

    if step < 3 or step == num_steps - 1:
      print(f"      Step {step}: batch shape={batch_arr.shape}, first_token={int(step_tokens[0][0])}")

  return sample_count


def _dump_groups(args):
  """Dump samples from every scatter group, mirroring antllm's check_outputs.py.

  antllm iterates `for rank in range(abs(loader_scatter))` where each rank
  represents one scatter group with `world_size=abs(scatter)`. This function
  replicates that: for each group, build a full-pipeline source (including
  multi-dataset blending, shuffle, and split) and consume batch_per_step
  samples sequentially per step.

  Output structure (single split):
    <output-dir>/<group_id>/step_<N>.npy
  Output structure (multiple splits, e.g. --split-parts train,valid):
    <output-dir>/train/<group_id>/step_<N>.npy
    <output-dir>/valid/<group_id>/step_<N>.npy
  """
  if not args.output_dir:
    raise ValueError("--dump-groups requires --output-dir")

  scatter = abs(args.loader_scatter)
  if scatter <= 1:
    raise ValueError("--dump-groups requires |loader_scatter| > 1")

  num_steps = args.num_steps
  batch_per_step = args.batch_per_step if args.batch_per_step else args.num_samples

  print(f"{'='*70}")
  print("Dumping ALL scatter groups (full pipeline: blend/shuffle/split)")
  print(f"{'='*70}")
  print(f"  loader_scatter={args.loader_scatter}, groups={scatter}")
  print(f"  scatter_dirs={args.scatter_dir}")
  print(f"  split_parts={args.split_parts}")
  print(f"  batch_per_step={batch_per_step}, num_steps={num_steps}")
  print(f"  output_dir={args.output_dir}")
  print()

  for group_id in range(scatter):
    print(f"  --- Group {group_id} (process_index={group_id}) ---")
    sources_dict = _build_source_for_group(args, process_index=group_id)
    multi_split = len(sources_dict) > 1

    for split_name, source in sources_dict.items():
      if multi_split:
        group_dir = os.path.join(args.output_dir, split_name, str(group_id))
      else:
        group_dir = os.path.join(args.output_dir, str(group_id))
      os.makedirs(group_dir, exist_ok=True)

      sample_count = _dump_split_source(source, split_name, group_dir, num_steps, batch_per_step)

      if num_steps > 4:
        print(f"      ... ({num_steps - 4} steps omitted)")
      print(f"      Total: {sample_count} samples saved to {group_dir}/")
    print()

  print(f"{'='*70}")
  if multi_split:
    print(f"Done. Output: {args.output_dir}/<split>/<group_id>/step_*.npy")
  else:
    print(f"Done. Output: {args.output_dir}/<group_id>/step_*.npy")
  print(f"{'='*70}")


def main():
  args = get_args()
  tic = time.time()

  if args.dump_groups:
    _dump_groups(args)
    return

  if args.debug_binary:
    for scatter_dir in args.scatter_dir:
      _debug_binary(scatter_dir, args.seq_length, args.eos_token_id, args.data_type, args.mode)

  print(f"Building data source (mode={args.mode})...")
  if args.raw:
    # Build only the MultiShardLazyDataSource (no blend/shuffle/split)
    effective_seq = args.seq_length + 1
    cls_token_id = args.cls_token_id if args.cls_token_id >= 0 else None
    source = MultiShardLazyDataSource(
        scatter_dir=args.scatter_dir[0],
        mode=args.mode,
        seq_length=effective_seq,
        eos_token_id=args.eos_token_id,
        data_type=args.data_type,
        cls_token_id=cls_token_id,
        add_cls=args.add_cls,
        drop_last=not args.no_drop_last,
        loader_online_shuffle=args.loader_online_shuffle,
        loader_seed=args.loader_seed,
        index_mapping_path=args.index_mapping_path,
        bin_index_base_path=args.bin_index_path,
        bfd_pack_sort_by_lens=args.bfd_pack_sort_by_lens,
        loader_scatter=args.loader_scatter,
        process_index=args.process_index,
    )
    print(f"  [RAW] shards={len(source._loaders)}, samples={len(source)}")
    print(f"  loader_online_shuffle={args.loader_online_shuffle}, loader_seed={args.loader_seed}")
    print(f"  loader_scatter={args.loader_scatter}, process_index={args.process_index}")
    sources_dict = {"train": source}
  else:
    sources_dict = build_source(args)
  build_time = time.time() - tic
  for name, src in sources_dict.items():
    print(f"Built [{name}] in {build_time:.2f}s, total samples: {len(src)}")

  if args.show_stats:
    print_dataset_stats(list(sources_dict.values())[0], args)

  # Load tokenizer if requested
  tokenizer = None
  if args.tokenizer_path and not args.no_decode:
    tokenizer = load_tokenizer(args.tokenizer_path)

  # Dump samples for each split part
  for split_name, source in sources_dict.items():
    multi_split = len(sources_dict) > 1
    if multi_split:
      split_output_dir = os.path.join(args.output_dir, split_name) if args.output_dir else None
    else:
      split_output_dir = args.output_dir

    if split_output_dir:
      os.makedirs(split_output_dir, exist_ok=True)

    end_index = min(args.start_index + args.num_samples, len(source))
    actual_count = end_index - args.start_index
    if actual_count <= 0:
      print(f"No samples to dump for [{split_name}] (start={args.start_index}, total={len(source)})")
      continue

    print(f"\nDumping [{split_name}] samples [{args.start_index}, {end_index})...")
    for i in range(args.start_index, end_index):
      if args.trace and not args.raw:
        _trace_sample(source, i)
      sample = source[i]
      # Source outputs seq_length+1 tokens (antllm convention).
      # Take inputs = text[:-1] to match training split (MegatronSplitInputsTargets).
      tokens = sample["text"] if isinstance(sample, dict) else sample
      tokens = np.asarray(tokens)[:-1]
      sample = {"text": tokens}
      dump_sample(i, sample, eos_token_id=args.eos_token_id, tokenizer=tokenizer, decode=not args.no_decode)

      if split_output_dir:
        np.save(os.path.join(split_output_dir, f"sample_{i:06d}.npy"), tokens)

    if split_output_dir:
      print(f"\nSaved {actual_count} [{split_name}] samples to {split_output_dir}/")

  print(f"\nTotal time: {time.time() - tic:.2f}s")


if __name__ == "__main__":
  main()
